SELECT ACCOUNTID,LOGINDATETIME,
LAG(LOGINDATETIME) OVER(PARTITION BY ACCOUNTID ORDER BY LOGINDATETIME )AS PRV_LOGIN,
DATEDIFF(
DAY,
LAG(LOGINDATETIME) OVER(PARTITION BY ACCOUNTID ORDER BY LOGINDATETIME ),LOGINDATETIME
) AS CURRENT_LOGIN
FROM STEAM_LOGIN_ACTIVITY
GROUP BY ACCOUNTID,LOGINDATETIME

