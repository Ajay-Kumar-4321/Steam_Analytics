SELECT PURCHASEID,PLATFORM,GAMETITLE,PRICE,RNK FROM 
(
SELECT PURCHASEID,PLATFORM,GAMETITLE,PRICE,
DENSE_RANK() OVER(PARTITION BY PLATFORM ORDER BY PRICE DESC) AS RNK
FROM STEAM_PURCHASES
GROUP BY PURCHASEID,PLATFORM,GAMETITLE,PRICE
) AS A
WHERE A.RNK IN (1,2,3)

