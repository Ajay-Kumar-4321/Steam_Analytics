CREATE OR ALTER PROCEDURE GetAccountRevenue
    @StartDate DATE,
    @EndDate   DATE
AS
BEGIN

    SELECT
        A.Username,
        A.Country,
        SUM(P.Price) AS TotalRevenue
    FROM STEAM_ACCOUNTS AS A
    JOIN STEAM_PURCHASES AS P ON A.AccountID = P.AccountID
    WHERE P.PurchaseDate BETWEEN @StartDate AND @EndDate
    GROUP BY A.Username, A.Country
    ORDER BY TotalRevenue DESC;
END

