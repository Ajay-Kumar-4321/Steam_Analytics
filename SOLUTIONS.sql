SELECT Country, TotalAccounts, InactiveCount, InactivePct
FROM (
    SELECT
        Country,
        COUNT(*) AS TotalAccounts,
        SUM(CASE
		WHEN AccountStatus IN ('Suspended','Deactivated') THEN 1 
		ELSE 0 
		END) AS InactiveCount,

        SUM(CASE WHEN AccountStatus IN ('Suspended','Deactivated') THEN 1 
		ELSE 0
		END) * 100.0 / COUNT(*) AS InactivePct
    FROM steam_accounts
    GROUP BY Country
) AS CountrySummary
WHERE InactivePct > 15
ORDER BY InactivePct DESC;

