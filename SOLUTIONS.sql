SELECT
    A.AccountID,
    A.Username,
    SUM(P.Price) AS TotalSpend
FROM  STEAM_ACCOUNTS AS A
JOIN STEAM_PURCHASES AS P ON A.AccountID = P.AccountID
GROUP BY A.AccountID, A.Username
HAVING SUM(P.Price) > 50
ORDER BY TotalSpend DESC;

--2.
SELECT A.AccountID,A.USERNAME,A.COUNTRY,COUNT(P.PURCHASEID) AS PURCHASE_COUNT,
RANK() OVER(PARTITION BY A.COUNTRY ORDER BY COUNT(P.PURCHASEID)DESC) CNTRY_RNK
FROM steam_accounts AS A
JOIN
steam_purchases AS P
ON A.AccountID=P.AccountID
GROUP BY A.AccountID,A.COUNTRY,A.Username
ORDER BY A.Country,CNTRY_RNK

--3.
SELECT MONTH(PURCHASEDATE) AS MONTHNUMBER,
DATENAME(MONTH,PURCHASEDATE) AS MONTHNAME,
COUNT(*) AS PURCHASE_COUNT,
SUM(PRICE) AS TOTAL_REVENUE
FROM STEAM_PURCHASES
WHERE YEAR(PURCHASEDATE)=2025
GROUP BY MONTH(PURCHASEDATE),DATENAME(MONTH,PURCHASEDATE)
ORDER BY MONTHNUMBER

