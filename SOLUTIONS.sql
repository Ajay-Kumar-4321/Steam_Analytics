SELECT YEAR(PURCHASEDATE) AS YEAR_,MONTH(PURCHASEDATE) AS MONTH_,SUM(PRICE) AS REVENUE,
SUM(SUM(PRICE)) OVER(ORDER BY YEAR(PURCHASEDATE),MONTH(PURCHASEDATE)
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW )AS RUNNING_TOTAL 
FROM STEAM_PURCHASES
GROUP BY YEAR(PURCHASEDATE),MONTH(PURCHASEDATE)

