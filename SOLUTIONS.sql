SELECT DEVICE,AVG(SESSIONMINUTES) AS AVERAGE,
CASE
WHEN
AVG(SESSIONMINUTES)>180 THEN 'HIGH'
ELSE 
'NORMAL'
END
AS FLAG
FROM STEAM_LOGIN_ACTIVITY
GROUP BY DEVICE
HAVING AVG(SESSIONMINUTES)>180
ORDER BY AVERAGE DESC

