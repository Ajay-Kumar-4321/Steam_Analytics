FROM STEAM_PURCHASES AS P
JOIN STEAM_ACCOUNTS AS A
ON P.ACCOUNTID=A.ACCOUNTID
GROUP BY A.ACCOUNTID,A.USERNAME
HAVING COUNT(PURCHASEID)>3
ORDER BY PURCHASE_COUNT DESC

